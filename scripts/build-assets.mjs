// Bundles gateway/static/* and gateways.json into gateway/assets.js, so every
// platform (Workers, Deno, Vercel, Netlify, Node) gets them without file access.
// Run after editing anything in gateway/static/:  npm run build
// `node scripts/build-assets.mjs --check` fails if assets.js is out of date (CI).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'gateway', 'static');
const assets = {};
for (const name of readdirSync(dir).sort()) assets[name] = readFileSync(join(dir, name), 'utf8');
const gateways = JSON.parse(readFileSync(join(root, 'gateways.json'), 'utf8')).gateways || [];

const out = `// Generated by scripts/build-assets.mjs. Do not edit: change gateway/static/ or gateways.json and run \`npm run build\`.
export const ASSETS = ${JSON.stringify(assets, null, 1)};
export const GATEWAYS = ${JSON.stringify(gateways, null, 1)};
`;
const file = join(root, 'gateway', 'assets.js');
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== out) { console.error('gateway/assets.js is out of date: run `npm run build`'); process.exit(1); }
  console.log('assets: up to date');
} else {
  writeFileSync(file, out);
  console.log(`assets: wrote ${Object.keys(assets).length} files, ${gateways.length} gateways`);
}
