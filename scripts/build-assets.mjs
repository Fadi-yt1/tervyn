// Bundles gateway/static/* and gateways.json into gateway/assets.js, so every
// platform (Workers, Deno, Vercel, Netlify, Node) gets them without file access.
// Run after editing anything in gateway/static/:  npm run build
// `node scripts/build-assets.mjs --check` fails if assets.js is out of date (CI).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'gateway', 'static');
const assets = {};
for (const name of readdirSync(dir).sort()) assets[name] = readFileSync(join(dir, name), 'utf8');
const gwFile = JSON.parse(readFileSync(join(root, 'gateways.json'), 'utf8'));
const gateways = gwFile.gateways || [];
// Optional: the address of your Tervyn Browser (remote Chrome), shown on the home page.
const browserUrl = /^https:\/\//.test(gwFile.browser || '') ? gwFile.browser.replace(/\/+$/, '') : '';

const out = `// Generated by scripts/build-assets.mjs. Do not edit: change gateway/static/ or gateways.json and run \`npm run build\`.
export const ASSETS = ${JSON.stringify(assets, null, 1)};
export const GATEWAYS = ${JSON.stringify(gateways, null, 1)};
export const BROWSER_URL = ${JSON.stringify(browserUrl)};
`;
// The static portal (GitHub Pages serves the repo root): the same home page, reading gateways.json.
const portal = {
  'index.html': assets['index.html']
    .replace('<head>', '<head>\n<!-- Generated from gateway/static/index.html by scripts/build-assets.mjs. -->\n<script>window.TERVYN_PORTAL = 1;</script>')
    .replace('href="/favicon.svg"', 'href="favicon.svg"')
    .replace('href="/__tervyn/about"', 'href="about.html"'),
  'about.html': assets['about.html'].replace('href="/favicon.svg"', 'href="favicon.svg"').replace('<a href="/">', '<a href="./">'),
  'favicon.svg': assets['favicon.svg'],
  '.nojekyll': '',
};
const files = { [join(root, 'gateway', 'assets.js')]: out };
for (const [name, text] of Object.entries(portal)) files[join(root, name)] = text;

if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([f, text]) => { try { return readFileSync(f, 'utf8') !== text; } catch { return true; } });
  if (stale.length) { console.error(`out of date: ${stale.map(([f]) => f.slice(root.length + 1)).join(', ')} (run \`npm run build\`)`); process.exit(1); }
  console.log('assets: up to date');
} else {
  for (const [f, text] of Object.entries(files)) writeFileSync(f, text);
  console.log(`assets: wrote ${Object.keys(assets).length} files + portal, ${gateways.length} gateways`);
}
